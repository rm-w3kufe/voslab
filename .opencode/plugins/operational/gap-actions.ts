/**
 * gap-actions.ts — Action executors for gap resolution.
 *
 * Executes actions based on gap evaluation results.
 * Supports semi-automatic (suggest) and automatic (execute) modes.
 */
import { existsSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs"
import { join, dirname, basename, extname } from "node:path"
import { execFile } from "node:child_process"
import { promisify } from "node:util"

const execFileP = promisify(execFile)

// ─── Types ───────────────────────────────────────────────────────────────────

export interface ActionResult {
  executed: boolean
  detail: string
}

// ─── Action Executors ──────────────────────────────────────────────────────

export async function executeAction(
  action: string,
  params: Record<string, any>,
  context: Record<string, any>,
  repoRoot: string,
  autoMode: boolean
): Promise<ActionResult> {
  switch (action) {
    case "move-file": {
      const source = context.filePath
      const targetDir = params.target || context.recommendedDirectory
      if (!targetDir) {
        return { executed: false, detail: "no target directory" }
      }

      const targetPath = join(repoRoot, targetDir, basename(source))

      if (autoMode) {
        // AUTOMATIC: move file directly
        try {
          mkdirSync(dirname(targetPath), { recursive: true })
          copyFileSync(source, targetPath)
          // Note: actual delete would need R17 consent
          return { executed: true, detail: `moved to ${targetDir}` }
        } catch (err: any) {
          return { executed: false, detail: err.message }
        }
      } else {
        // SEMI-AUTOMATIC: suggest move
        return {
          executed: false,
          detail: `SUGGEST: move ${basename(source)} to ${targetDir}`,
        }
      }
    }

    case "create-handler": {
      const scriptName = context.fileName?.replace(/\.(py|sh)$/, "")
      const category = context.directory?.match(/scripts\/state\/(\w+)/)?.[1] || "unknown"
      const handlerPath = join(repoRoot, ".opencode/plugins/operational/handlers", `${category}-auto.ts`)

      if (existsSync(handlerPath)) {
        return { executed: false, detail: `handler already exists: ${category}-auto.ts` }
      }

      if (autoMode) {
        // AUTOMATIC: create handler (SANDBOX: generated code uses
        // execFile+argv, never shell — the old template interpolated
        // paths into exec(), a command-injection shape by construction).
        const handlerContent = `
/**
 * ${category}-auto.ts — auto-created handler for ${category} scripts.
 * Generated by gap-resolver.ts (sandboxed: execFile-only, no shell).
 */
import { execFile } from "node:child_process"
import { promisify } from "node:util"
import { existsSync } from "node:fs"
import { join, resolve, relative, isAbsolute } from "node:path"
import type { Handler } from "./vsf-event-router"

const execFileP = promisify(execFile)

export const ${category}AutoHandler: Handler = {
  id: "${category}-auto",
  priority: 5,
  events: ["session.idle"],
  classify: async () => true,
  execute: async (ctx) => {
    const script = resolve(join(ctx.repoRoot, "scripts/state/${category}/${scriptName}${extname(context.filePath)}"))
    if (!isAbsolute(script)) return { result: "skip", durationMs: 0, detail: "not absolute" }
    if (relative(ctx.repoRoot, script).startsWith("..")) return { result: "skip", durationMs: 0, detail: "outside root" }
    if (!existsSync(script)) return { result: "skip", durationMs: 0, detail: "not found" }
    try {
      const ext = script.endsWith(".py") ? "python3" : "bash"
      await execFileP(ext, [script], { cwd: ctx.repoRoot, timeout: 30_000, maxBuffer: 10 * 1024 * 1024 })
      return { result: "pass", durationMs: 0, detail: "executed" }
    } catch (err: any) {
      return { result: "fail", durationMs: 0, detail: err.message?.slice(0, 200) }
    }
  },
}
`
        writeFileSync(handlerPath, handlerContent)
        return { executed: true, detail: `created handler: ${category}-auto.ts` }
      } else {
        // SEMI-AUTOMATIC: suggest creation
        return {
          executed: false,
          detail: `SUGGEST: create handler for ${category}/${scriptName}`,
        }
      }
    }

    case "alert-conflict": {
      const message = params.message || "Conflict detected"
      return { executed: false, detail: `ALERT: ${message}` }
    }

    case "block-commit": {
      const reason = params.reason || "Quality gate failed"
      return { executed: false, detail: `BLOCK: ${reason}` }
    }

    case "log-success": {
      return { executed: true, detail: "OK" }
    }

    case "run-script": {
      // Programmatic action (S5 2026-10-02: covenant procedure must be
      // driven from the decision tree). execFile+argv, never a shell.
      // `safe: true` marks a read-only or self-reversing script that may
      // run in semi-automatic mode; everything else is suggested only
      // (auto mode runs either).
      const argv: string[] = Array.isArray(params.argv) ? params.argv : []
      if (argv.length === 0) {
        return { executed: false, detail: "run-script: params.argv (array) required" }
      }
      const printable = argv.map(String).join(" ")
      const safe = params.safe === true
      if (!autoMode && !safe) {
        return { executed: false, detail: `MANUAL (not auto-safe): ${printable}` }
      }
      try {
        const { stdout } = await execFileP(String(argv[0]), argv.slice(1).map(String), {
          cwd: repoRoot,
          timeout: Number(params.timeoutMs) || 60000,
          maxBuffer: 8 * 1024 * 1024,
        })
        const tail = stdout.trim().split("\n").slice(-4).join(" | ")
        return { executed: true, detail: `${printable} → ${(tail || "ok").slice(0, 300)}` }
      } catch (err: any) {
        const out = String(err?.stdout || "")
        const tail = out.trim().split("\n").slice(-2).join(" | ")
        return {
          executed: false,
          detail: `${printable} FAILED (rc=${err?.code ?? "?"}): ${tail || String(err?.message || "").slice(0, 200)}`,
        }
      }
    }

    case "show-s5-commands": {
      // Always executes: PRINTING the manual S5 block is read-only — the
      // block itself is regenerated on demand (so the gap definition can
      // never go stale) and surfaced to the session console + activation
      // log. The S5 actions themselves remain manual by design (root on
      // n01; R17 — nothing destructive without explicit confirmation).
      const argv: string[] = Array.isArray(params.argv) ? params.argv : []
      if (argv.length === 0) {
        return { executed: false, detail: "show-s5-commands: params.argv (array) required" }
      }
      try {
        const { stdout } = await execFileP(String(argv[0]), argv.slice(1).map(String), {
          cwd: repoRoot,
          timeout: Number(params.timeoutMs) || 60000,
          maxBuffer: 8 * 1024 * 1024,
        })
        console.log("\n" + stdout)
        const lines = stdout.split("\n").length
        return { executed: true, detail: `S5 block printed (${lines} lines, regenerable via: ${argv.map(String).join(" ")})` }
      } catch (err: any) {
        return {
          executed: false,
          detail: `show-s5-commands FAILED: ${String(err?.message || "").slice(0, 200)}`,
        }
      }
    }

    default:
      return { executed: false, detail: `unknown action: ${action}` }
  }
}
