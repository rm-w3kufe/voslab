if __name__ == "__main__":
    # Self-test
    ts = vsm_timestamp()
    dt = vsm_date()
    print(f"Timestamp: {ts}")
    print(f"Date: {dt}")
    print(f"Valid: {validate_timestamp(ts)}")
    print(f"Hardcoded: {is_hardcoded_timestamp(ts)}")
    print(f"Hardcoded placeholder: {is_hardcoded_timestamp('2026-01-01T00:00:00Z')}")
