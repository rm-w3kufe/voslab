#!/usr/bin/env python3
"""gen_index.py — deterministic MEMORY.md generator (de-VS-ed from vsf).

Reads every *.md file in a memory directory, extracts frontmatter, and
regenerates an index grouped by type.

design: child/docs/voslab_packaging_proposal.vsm §catalog ("vsf-tools")

De-VS-ed: the storage directory is **injected** (constructor arg / --dir /
VSF_MEMORY_DIR), not hardcoded to ~/vsf. Stdlib only — reusable by any project.

Frontmatter format (required for each memory file):
    ---
    name: "My Memory"
    description: "What this memory is about (≤12 words)"
    metadata:
      type: project | reference | feedback | user
    ---

ORDER: Grouped by type, then by name alphabetically within each group.
Returns:
    0  ← generated OK or no drift
    1  ← drift detected (--check mode)
    2  ← error (malformed frontmatter, etc.)
"""
import argparse
import os
import re
import sys

TYPE_ORDER = {"user": 0, "feedback": 1, "project": 2, "reference": 3}
TYPE_LABELS = {0: "User", 1: "Feedback", 2: "Project", 3: "Reference"}


class MemoryIndexGenerator:
    """Generate a MEMORY.md index from a memory directory. Storage is injected."""

    def __init__(self, memory_dir: str):
        self.memory_dir = memory_dir
        self.memory_file = os.path.join(memory_dir, "MEMORY.md")

    # ------------------------------------------------------------------ #
    def parse_frontmatter(self, path: str) -> dict:
        """Extract frontmatter from a .md file.

        Returns dict with keys: name, description, type. On parse failure,
        returns a minimal dict with name=filename.
        """
        result = {"name": os.path.splitext(os.path.basename(path))[0],
                  "description": "", "type": "reference"}
        try:
            with open(path, encoding="utf-8") as fh:
                content = fh.read()
        except (IOError, OSError):
            return result

        if not content.startswith("---"):
            return result
        end = content.find("---", 3)
        if end == -1:
            return result
        front = content[3:end].strip()

        current_key = None
        for line in front.split("\n"):
            line = line.strip()
            if not line:
                continue
            m = re.match(r'^(\w+)\s*:\s*"?([^"\n]+?)"?\s*$', line)
            if m:
                key, val = m.group(1), m.group(2).strip().strip('"')
                current_key = None
                if key in ("name", "type"):
                    result[key] = val
                elif key == "description":
                    result["description"] = val
                elif key == "metadata.type":
                    result["type"] = val
                continue
            if re.match(r'^metadata\s*:', line):
                current_key = "metadata"
                continue
            if current_key == "metadata":
                m = re.match(r'^\s+(\w+)\s*:\s*"?([^"\n]+?)"?\s*$', line)
                if m and m.group(1) == "type":
                    result["type"] = m.group(2).strip().strip('"')
        if result["type"] not in TYPE_ORDER:
            result["type"] = "reference"
        return result

    def scan(self) -> list:
        """Scan memory_dir for .md files (excluding MEMORY.md/README.md)."""
        entries = []
        if not os.path.isdir(self.memory_dir):
            return entries
        for fn in sorted(os.listdir(self.memory_dir)):
            if not fn.endswith(".md") or fn in ("MEMORY.md", "README.md"):
                continue
            fp = os.path.join(self.memory_dir, fn)
            if not os.path.isfile(fp):
                continue
            front = self.parse_frontmatter(fp)
            entries.append({
                "name": front.get("name", fn.replace(".md", "")),
                "description": front.get("description", ""),
                "type": front.get("type", "reference"),
                "file": fn, "filename": fn,
                "_frontmatter_missing": front.get("name") == fn.replace(".md", ""),
            })
        return entries

    def generate(self, entries: list) -> str:
        """Generate the MEMORY.md content from entries."""
        lines = ["# Memory Index", "",
                 "<!-- GENERATED by vsf_tools.gen_index — DO NOT EDIT manually -->", ""]
        lines.append("Memory files are the single source of truth. "
                     "This index is derived from frontmatter in each file.")
        lines.append("")
        groups = {}
        for e in entries:
            groups.setdefault(TYPE_ORDER.get(e["type"], 3), []).append(e)
        if not groups:
            lines.append("_No memory files found._")
        else:
            for t in sorted(groups.keys()):
                lines.append(f"## {TYPE_LABELS.get(t, 'Other')}")
                lines.append("")
                for e in sorted(groups[t], key=lambda x: x["name"].lower()):
                    desc = e["description"]
                    if desc:
                        short = desc[:55] + "..." if len(desc) > 55 else desc
                        entry = f'- **[{e["name"]}]({e["file"]})** — {short}'
                    else:
                        entry = f'- **[{e["name"]}]({e["file"]})**'
                    entry += f'  | `{e["type"]}`'
                    if e.get("_frontmatter_missing"):
                        entry += ' ⚠ (no frontmatter — using filename)'
                    lines.append(entry)
                lines.append("")
        lines.append("---")
        lines.append(f"_{len(entries)} file(s)_")
        lines.append("")
        return "\n".join(lines)

    def check_links(self, entries: list, index_content: str) -> list:
        """Check that [[links]] in memory files point to valid entry names."""
        findings = []
        name_set = {e["name"] for e in entries}
        for e in entries:
            fp = os.path.join(self.memory_dir, e["file"])
            try:
                with open(fp, encoding="utf-8") as fh:
                    content = fh.read()
            except (IOError, OSError):
                continue
            for m in re.finditer(r'\[\[([^\]]+)\]\]', content):
                target = m.group(1)
                if target not in name_set:
                    findings.append({"file": e["file"], "link": target,
                                     "detail": f'Broken [[link]] to "{target}" in {e["file"]}'})
        return findings

    def write(self) -> str:
        entries = self.scan()
        output = self.generate(entries)
        os.makedirs(self.memory_dir, exist_ok=True)
        with open(self.memory_file, "w", encoding="utf-8") as fh:
            fh.write(output)
        return output

    def check_drift(self) -> int:
        if not os.path.exists(self.memory_file):
            return 1
        with open(self.memory_file, encoding="utf-8") as fh:
            existing = fh.read()
        return 0 if existing == self.generate(self.scan()) else 1


def _resolve_memory_dir(argv_dir: str | None) -> str:
    if argv_dir:
        return argv_dir
    env = os.environ.get("VSF_MEMORY_DIR")
    if env:
        return env
    return os.path.join(os.getcwd(), "docs", "memory")


def main(argv: list) -> int:
    p = argparse.ArgumentParser(description="MEMORY.md generator (de-VS-ed)")
    p.add_argument("--dir", help="memory directory (else VSF_MEMORY_DIR else ./docs/memory)")
    p.add_argument("--check", action="store_true", help="fail if MEMORY.md drifts")
    p.add_argument("--dry-run", action="store_true", help="print generated index, no write")
    p.add_argument("--verbose", action="store_true", help="show per-file details")
    a = p.parse_args(argv[1:])

    memory_dir = _resolve_memory_dir(a.dir)
    g = MemoryIndexGenerator(memory_dir)

    if a.verbose:
        entries = g.scan()
        print(f"Scanned {memory_dir}: {len(entries)} file(s)")
        for e in sorted(entries, key=lambda x: (x["type"], x["name"])):
            fm = "✓" if not e.get("_frontmatter_missing") else "⚠ (no frontmatter)"
            print(f'  {fm} [{e["type"]}] {e["name"]}: {e["description"][:40]}')

    output = g.generate(g.scan())
    link_issues = g.check_links(g.scan(), output)
    for issue in link_issues:
        print(f'  ⚠ {issue["detail"]}', file=sys.stderr)

    if a.check:
        code = g.check_drift()
        if code == 0:
            print("MEMORY.md: no drift detected.")
        else:
            print("MEMORY.md: DRIFT detected! Regenerate with gen_index.", file=sys.stderr)
        if link_issues:
            print(f"{len(link_issues)} broken [[link]](s) found.", file=sys.stderr)
            return 1
        return code

    if a.dry_run:
        print(output)
        return 0

    g.write()
    print(f"Generated {g.memory_file}")
    if link_issues:
        print(f"Warning: {len(link_issues)} broken [[link]](s) found (non-fatal).")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
