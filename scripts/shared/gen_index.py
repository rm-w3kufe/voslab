#!/usr/bin/env python3
"""
MEMORY.md generator — VSL-STANDARDIZATION v1.5 memory index.

Reads every docs/memory/*.md file, extracts frontmatter, and regenerates
MEMORY.md deterministically.

Frontmatter format (required for each memory file):
    ---
    name: "My Memory"
    description: "What this memory is about (≤12 words)"
    metadata:
      type: project | reference | feedback | user
    ---

ORDER: Grouped by type, then by name alphabetically within each group.
If no frontmatter is found, the generator falls back to filename.

Usage:
    python3 scripts/memory/gen_index.py              # generate MEMORY.md
    python3 scripts/memory/gen_index.py --check      # fail if drift (non-zero exit)
    python3 scripts/memory/gen_index.py --dry-run    # print what would be generated
    python3 scripts/memory/gen_index.py --verbose    # show per-file details

Returns:
    0  ← generated OK or no drift
    1  ← drift detected (--check mode)
    2  ← error (malformed frontmatter, etc.)
"""

from pathlib import Path
import argparse
import os
import re
import sys

# S5 containment 2026-10-04: workspace root default (VSF_ROOT env still
# wins for upstream/covenant workflows).
VSF_ROOT = os.environ.get("VSF_ROOT") or os.environ.get("VOSLAB_PATH") \
    or str(Path(__file__).resolve().parents[2])
MEMORY_DIR = os.path.join(VSF_ROOT, "docs", "memory")
MEMORY_FILE = os.path.join(VSF_ROOT, "docs", "memory", "MEMORY.md")

TYPE_ORDER = {"user": 0, "feedback": 1, "project": 2, "reference": 3}
TYPE_LABELS = {0: "User", 1: "Feedback", 2: "Project", 3: "Reference"}


def parse_frontmatter(path: str) -> dict:
    """
    Extract YAML-like frontmatter from a .md file.

    Returns dict with keys: name, description, type.
    On parse failure, returns minimal dict with name=filename.
    """
    result = {"name": os.path.splitext(os.path.basename(path))[0],
              "description": "",
              "type": "reference"}

    try:
        with open(path, encoding="utf-8") as fh:
            content = fh.read()
    except (IOError, OSError) as e:
        return result  # fallback to filename

    # Look for frontmatter delimited by ---
    if not content.startswith("---"):
        return result

    end = content.find("---", 3)
    if end == -1:
        return result

    front = content[3:end].strip()

    # Simple line-based parsing (not full YAML — matches VSL frontmatter style)
    current_key = None
    for line in front.split("\n"):
        line = line.strip()
        if not line:
            continue

        # Top-level key: value
        m = re.match(r'^(\w+)\s*:\s*"(.+)"\s*$', line)
        if m:
            key, val = m.group(1), m.group(2)
            current_key = None
            if key == "name":
                result["name"] = val
            elif key == "description":
                result["description"] = val
            elif key == "metadata.type":
                result["type"] = val
            elif key == "type":
                result["type"] = val
            continue

        # Nested key
        m = re.match(r'^(\w+)\s*:\s*"(.+)"\s*$', line)
        if m:
            key, val = m.group(1), m.group(2)
            if key == "type":
                result["type"] = val
                current_key = None
                continue

        # metadata: key is set → next indent-level key
        m = re.match(r'^metadata\s*:', line)
        if m:
            current_key = "metadata"
            continue

        # Indented key under metadata
        if current_key == "metadata":
            m = re.match(r'^\s+(\w+)\s*:\s*"(.+)"\s*$', line)
            if m:
                k, v = m.group(1), m.group(2)
                if k == "type":
                    result["type"] = v

    # Validate type
    if result["type"] not in TYPE_ORDER:
        result["type"] = "reference"  # default fallback

    return result


def scan_memory_files(path: str) -> list:
    """
    Scan MEMORY_DIR for .md files (excluding MEMORY.md itself).
    Returns list of dicts: {name, description, type, file, filename}.
    """
    entries = []
    if not os.path.isdir(path):
        return entries

    for fn in sorted(os.listdir(path)):
        if not fn.endswith(".md") or fn == "MEMORY.md" or fn == "README.md":
            continue
        fp = os.path.join(path, fn)
        if not os.path.isfile(fp):
            continue
        front = parse_frontmatter(fp)
        entries.append({
            "name": front.get("name", fn.replace(".md", "")),
            "description": front.get("description", ""),
            "type": front.get("type", "reference"),
            "file": fn,
            "filename": fn,
            "_frontmatter_missing": front.get("name") == fn.replace(".md", ""),
        })

    return entries


def generate_index(entries: list) -> str:
    """Generate the MEMORY.md content from entries."""
    lines = []
    lines.append("# Memory Index")
    lines.append("")
    lines.append("<!-- GENERATED by scripts/memory/gen_index.py -- DO NOT EDIT manually -->")
    lines.append("<!-- Run `python3 scripts/memory/gen_index.py` to regenerate -->")
    lines.append("")
    lines.append(
        "Memory files are the single source of truth. "
        "This index is derived from frontmatter in each file."
    )
    lines.append("")

    # Group by type
    groups = {}
    for e in entries:
        t = TYPE_ORDER.get(e["type"], 3)
        groups.setdefault(t, []).append(e)

    if not groups:
        lines.append("_No memory files found._")
    else:
        for type_order in sorted(groups.keys()):
            label = TYPE_LABELS.get(type_order, "Other")
            group = groups[type_order]
            lines.append(f"## {label}")
            lines.append("")
            for e in sorted(group, key=lambda x: x["name"].lower()):
                desc = e["description"]
                if desc:
                    desc_short = desc[:55] + "..." if len(desc) > 55 else desc
                    entry = f'- **[{e["name"]}]({e["file"]})** — {desc_short}'
                else:
                    entry = f'- **[{e["name"]}]({e["file"]}**'
                entry += f'  | `{e["type"]}`'
                if e.get("_frontmatter_missing"):
                    entry += ' ⚠ (no frontmatter — using filename)'
                lines.append(entry)
            lines.append("")

    lines.append("---")
    lines.append(f"_{len(entries)} file(s)_")
    lines.append("")

    return "\n".join(lines)


def check_links(entries: list, index_content: str) -> list:
    """Check that [[links]] in memory files point to valid entry names."""
    findings = []
    name_set = {e["name"] for e in entries}

    for e in entries:
        fp = os.path.join(MEMORY_DIR, e["file"])
        try:
            with open(fp, encoding="utf-8") as fh:
                content = fh.read()
        except (IOError, OSError):
            continue

        for m in re.finditer(r'\[\[([^\]]+)\]\]', content):
            target = m.group(1)
            if target not in name_set:
                findings.append({
                    "file": e["file"],
                    "link": target,
                    "detail": f'Broken [[link]] to "{target}" in {e["file"]}',
                })

    return findings


def main(argv: list) -> int:
    p = argparse.ArgumentParser(description="MEMORY.md generator (VSL-STANDARDIZATION v1.5)")
    p.add_argument("--check", action="store_true",
                   help="Check for drift (fail if MEMORY.md != generated output)")
    p.add_argument("--dry-run", action="store_true",
                   help="Print generated index without writing")
    p.add_argument("--verbose", action="store_true",
                   help="Show per-file frontmatter details")
    a = p.parse_args(argv[1:])

    # Ensure MEMORY_DIR exists
    if not os.path.isdir(MEMORY_DIR):
        os.makedirs(MEMORY_DIR, exist_ok=True)

    entries = scan_memory_files(MEMORY_DIR)

    if a.verbose:
        print(f"Scanned {MEMORY_DIR}: {len(entries)} file(s)")
        for e in sorted(entries, key=lambda x: (x["type"], x["name"])):
            fm = "✓" if not e.get("_frontmatter_missing") else "⚠ (no frontmatter)"
            print(f'  {fm} [{e["type"]}] {e["name"]}: {e["description"][:40]}')

    output = generate_index(entries)

    # Check [[links]] (all modes)
    link_issues = check_links(entries, output)
    for issue in link_issues:
        print(f'  ⚠ {issue["detail"]}', file=sys.stderr)

    if a.check:
        if not os.path.exists(MEMORY_FILE):
            print(f"ERROR: MEMORY.md not found at {MEMORY_FILE} — run gen_index.py first",
                  file=sys.stderr)
            return 1

        with open(MEMORY_FILE, encoding="utf-8") as fh:
            existing = fh.read()

        if existing == output:
            print("MEMORY.md: no drift detected.")
            drift_code = 0
        else:
            print("MEMORY.md: DRIFT detected! Regenerate with gen_index.py", file=sys.stderr)
            drift_code = 1

        if link_issues:
            print(f"{len(link_issues)} broken [[link]](s) found.", file=sys.stderr)
            return 1

        return drift_code

    if a.dry_run:
        print(output)
        return 0

    with open(MEMORY_FILE, "w", encoding="utf-8") as fh:
        fh.write(output)
    print(f"Generated {MEMORY_FILE} ({len(entries)} file(s), {len(output)} chars)")
    if link_issues:
        print(f"Warning: {len(link_issues)} broken [[link]](s) found (non-fatal in write mode)")

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
