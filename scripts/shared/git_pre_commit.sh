#!/usr/bin/env bash
# VSF docs index + secret guard — pre-commit hook (versioned source).
# Keeps docs/INDEX.md + docs/.index.db current on EVERY commit (local, no network),
# AND blocks commits that leak credentials in the Wazuh-pwgen format.
#
# Install (per clone — git hooks are not versioned):
#   ln -sf ../../scripts/shared/git_pre_commit.sh .git/hooks/pre-commit
#   (or: cp scripts/shared/git_pre_commit.sh .git/hooks/pre-commit && chmod +x .git/hooks/pre-commit)
#
# Three blocks:
#   (A) SECRET GUARD — BLOCKING. If any STAGED content matches a known leaked
#       credential pattern (Wazuh-pwgen format, or the literal fingerprints
#       from the 2026-08-02 install), reject the commit with exit 1.
#       Rationale: a leaked credential cannot be "fixed in a follow-up" — once
#       in git history it must be scrubbed with filter-repo. Fail hard, force
#       the operator to handle it.
#   (B) DOCS INDEX — non-blocking. UPDATES the index; never rejects (operator
#       chose the commit-loop over a periodic --check gate). Run
#       docs_reconcile.py manually to audit drift if desired.
#   (C) VSL BOOT PRIMER STALENESS — BLOCKING. If a commit touches one of the
#       5 canonical sources the compressed VSL boot primer (docs/spec/
#       agent_protocol/vsl_*_v1.vsm) was compressed from, without the primer's
#       own hash-manifest being updated in the same commit, reject with exit 1.
#       Rationale: this is the exact "hand-written doc silently drifts from
#       its source" disease the 2026-08-03 axiom-consistency audit spent a
#       whole session finding across CLAUDE.md/README/BRIEFING.vsf.md/vos_
#       architecture.vsm. The primer was built specifically to not repeat
#       that pattern -- this hook is what makes the guarantee real instead of
#       aspirational. Override ONCE with VSF_SKIP_PRIMER_GUARD=1 if a source
#       edit genuinely can't be re-verified immediately; document why in the
#       commit message. Do NOT silence by removing the hook.
set -e
ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"

# skip() — if .git is a file (git worktree), exit 0 without touching the index.
# Worktree commits share the main repo's objects but operate on a separate
# working tree; running docs_reconcile.py --update from a worktree would write
# INDEX.md in the worktree context, not the canonical repo tree.
skip() {
  if [ -f "$ROOT/.git" ]; then
    exit 0
  fi
}
skip

# ── (A) SECRET GUARD — blocking ────────────────────────────────────────────
# Scans ONLY staged content (not the whole tree — fast, and avoids stale
# hits from already-accepted history).
#
# Detection triple mode:
#   1. Literal fingerprints: the specific credential strings generated by the
#      Wazuh installer on 2026-08-02 (well-formedness check — catches them even
#      if a future pwgen ever happens to share the format by accident).
#   2. Generic Wazuh-pwgen format: ~30-40 char tokens drawn from the charset
#      [A-Za-z0-9?*.+] containing at least one of ? * + .
#      (Wazuh's generator always emits them; bare base64 lacks these).
#      Anchored to plausible assignment/payload shapes to minimize false positives.
#   3. NATS token auth: hex-32 token ANCHORED to NATS context (nats://<hex32>@
#      or NATS_TOKEN=<hex32>). Added 2026-08-03 after the production NATS token
#      was found committed in s1_econ_kernel.py:46 default + state.json:57.
#      Anchor avoids FP on git SHAs / UUIDs, which are also hex-32 shaped.
# Scope: 2-3: *.vsm *.md *.sh *.py *.rs *.json *.yaml *.yml *.toml *.txt
# Bypass: set VSF_SKIP_SECRET_GUARD=1 in the env (use sparingly; record why).

guard_secret() {
  if [ "${VSF_SKIP_SECRET_GUARD:-0}" = "1" ]; then
    return 0
  fi

  # Files staged for this commit, filtered to text-y types we care about.
  local staged
  staged=$(git diff --cached --name-only --diff-filter=AM -- \
            '*.vsm' '*.md' '*.sh' '*.py' '*.rs' '*.json' '*.yaml' '*.yml' \
            '*.toml' '*.txt' 2>/dev/null || true)
  [ -z "$staged" ] && return 0

  # Regex (extended): Wazuh-pwgen token — 28-44 chars from the special charset,
  # MUST contain at least one of ? * + (the canonical special markers), plus
  # alnum and '.'. Anchored by surrounding non-token context (quote, =, space,
  # colon) to avoid matching inside hashes/uuids.
  local pw_re='[[:space:]="'\'':]([][A-Za-z0-9.?*+]{28,44})([[:space:]"'\'',;}]|$)'

  local leaks=() file content hit
  for file in $staged; do
    # Skip the hook's own source (it contains the regex, not a real password).
    case "$file" in
      scripts/shared/git_pre_commit.sh) continue ;;
    esac
    # Binary-safe read; ignore files that fail to decode.
    content=$(git show ":$file" 2>/dev/null) || continue

    # (1) literal fingerprints — the 2026-08-02 install credentials
    if printf '%s' "$content" | grep -qE 'nS\?6I6i21R6TpGcAM|1\?PqN\?p\*RWPD|XhfSkLg57k|WFwqKzMOt|m9NQPp\?usUN|wUHNe89oU'; then
      leaks+=("$file (literal Wazuh install credential 2026-08-02)")
      continue
    fi

    # (2) generic Wazuh-pwgen format: must contain ? OR * OR + as the
    #     distinguished special (bare base64 has neither); require at least
    #     one such char inside a 28-44 char candidate token.
    #     The special must live INSIDE the candidate token, not merely
    #     somewhere on the same line. The first version piped whole matched
    #     LINES into the second grep, so any line carrying a 28-44 char token
    #     AND an unrelated *, ? or + tripped it. Live false positive
    #     2026-08-09: `"crosscheck.metrics.reconciled": "topology_reconcile
    #     exit (S3*)"` — a 30-char dotted identifier, with the `*` coming from
    #     `S3*` further along the line. grep -oE emits the candidate itself, so
    #     the test now applies to the token. This is strictly TIGHTER, not
    #     weaker: a real pwgen credential carries its special inside itself.
    #     Then drop one shape that is NOT a credential and keeps recurring:
    #     a list of git SHORT HASHES joined by '+'. Those are lowercase hex
    #     runs, they carry the '+' inside the token, and they survive the
    #     token-level test above. This has now blocked three commits — twice
    #     for DS on the same pre-existing HANDOFF line written 2026-06-19
    #     (9c59e3d+615de43+6abaf85+ce38732), each time forcing a documented
    #     override on a string that is provably a commit list.
    #     A pwgen credential is mixed-case over a wide alphabet; a hash list
    #     is [0-9a-f]{6,40} segments and nothing else. Excluding exactly that
    #     shape loses no real credential.
    #     The final stage MUST be a POSITIVE test. `grep -qv PATTERN` on EMPTY
    #     stdin exits 0 on this grep, so ending the pipe with -qv makes a file
    #     containing ZERO candidates report a leak — it would have blocked
    #     every commit in the repository. Caught by negative-testing all four
    #     cases instead of accepting three-of-four.
    if printf '%s' "$content" | grep -oE "$pw_re" \
         | grep -E '[?*+]' \
         | grep -vE '^[^A-Za-z0-9]?[0-9a-f]{6,40}(\+[0-9a-f]{6,40})+[^A-Za-z0-9]?$' \
         | grep -q .; then
      leaks+=("$file (Wazuh-pwgen format credential candidate)")
    fi

    # (3) NATS token auth — hex-32 token anchored to NATS context, so git SHAs /
    #     UUIDs (which are also hex-32 shaped) do not false-positive. Catches
    #     `nats://<hex32>@host` and `NATS_TOKEN=<hex32>` (the two canonical NATS
    #     token-auth shapes; real value discovered 2026-08-03 in s1_econ_kernel.
    #     py:46 default + state.json:57). The anchor is the NATS token or the
    #     nats:// URL scheme — not the bare hex string.
    local hex32='[0-9a-f]{32}'
    if printf '%s' "$content" | grep -qE "nats://${hex32}@"; then
      leaks+=("$file (NATS token auth URL — hex-32 token embedded)")
    fi
    if printf '%s' "$content" | grep -qE "NATS_TOKEN=['\"]?${hex32}['\"]?"; then
      leaks+=("$file (NATS_TOKEN hex-32 credential)")
    fi
  done

  if [ ${#leaks[@]} -gt 0 ]; then
    echo "❌ VSF secret guard: potential credential leak in staged content." >&2
    echo "    blocking commit. Files flagged:" >&2
    printf '      %s\n' "${leaks[@]}" >&2
    echo "" >&2
    echo "    If this is a false positive, override ONCE with:" >&2
    echo "      VSF_SKIP_SECRET_GUARD=1 git commit ..." >&2
    echo "    and document the FP reason in the commit message." >&2
    echo "    Do NOT silence the guard by removing the hook." >&2
    exit 1
  fi
}
guard_secret

# ── (B) DOCS INDEX — non-blocking ───────────────────────────────────────────
python3 scripts/shared/docs_reconcile.py --update >/dev/null 2>&1 || true
git add docs/INDEX.md 2>/dev/null || true

# ── (C) VSL BOOT PRIMER STALENESS — BLOCKING ────────────────────────────────
guard_primer_staleness() {
  if [ "${VSF_SKIP_PRIMER_GUARD:-0}" = "1" ]; then
    echo "⚠️  VSF_SKIP_PRIMER_GUARD=1 set — skipping boot-primer staleness check." >&2
    return 0
  fi
  if [ ! -f scripts/vsl/validator/verify_boot_primer.py ]; then
    return 0  # script not present in this checkout state — nothing to enforce
  fi
  if ! python3 scripts/vsl/validator/verify_boot_primer.py; then
    echo "" >&2
    echo "❌ VSF boot-primer guard: a canonical source changed without the" >&2
    echo "    compressed VSL primer being re-verified. Blocking commit." >&2
    echo "    Fix: re-check system/boot/*.vsm against the" >&2
    echo "    changed source(s) above, then:" >&2
    echo "      python3 scripts/vsl/validator/verify_boot_primer.py --update" >&2
    echo "    Override ONCE (document why in the commit message):" >&2
    echo "      VSF_SKIP_PRIMER_GUARD=1 git commit ..." >&2
    exit 1
  fi
}
guard_primer_staleness

# ── (D) VSL PRIMER NOTATION CLOSURE — BLOCKING ──────────────────────────────
# The primer must define every glyph it uses, IN ITSELF. That is what makes it
# portable to an agent that has never read vsm_notation_spec.md. Found
# 2026-08-04: the prose canon declares `⟹` as "Escalation" in its Part I table
# while using it as logical implication in its own axioms, and uses `⊤` without
# ever declaring it -- collisions a human patches over silently and an external
# agent cannot. Override with VSF_SKIP_PRIMER_GUARD=1 (same switch as block C).
guard_primer_closure() {
  if [ "${VSF_SKIP_PRIMER_GUARD:-0}" = "1" ]; then
    return 0
  fi
  if [ ! -f scripts/vsl/validator/verify_primer_closure.py ]; then
    return 0
  fi
  if ! python3 scripts/vsl/validator/verify_primer_closure.py; then
    echo "" >&2
    echo "❌ VSF primer-closure guard: the boot primer uses a symbol it never" >&2
    echo "    declares. Blocking commit -- an undeclared sign is precisely what" >&2
    echo "    a zero-context external agent cannot resolve." >&2
    echo "    Fix: declare it in the primer's notation{} section, or replace it" >&2
    echo "    with a glyph already declared there." >&2
    exit 1
  fi
}
guard_primer_closure


# ── (E) SPEC_REVISION ENCODING + NOTATION — BLOCKING ────────────────────────
# Added 2026-08-07. Blocks C and D cover the PRIMER only. Everything else in
# docs/spec_revision had no gate at all: a ⇒ (wrong arrow family), a ⚠
# (NO-EMOJIS rule, rmw3 2026-08-06), a missing ⟦4-field⟧ header or a mixed
# Unicode normalisation would all commit clean. That is how the corpus
# accumulated the defects this session spent a day finding by hand.
#
# Two checks, both deterministic, both stdlib-only (R10):
#   verify_encoding.py       UTF-8 · NFC · ¬BOM · ¬invisible · ⟦4⟧ · NO-EMOJIS
#   symbol_table.py --undeclared   every glyph used is declared somewhere
#
# Override with VSF_SKIP_SPEC_GUARD=1 -- for a deliberate mid-fuse commit,
# never to silence a finding.
guard_spec_revision() {
  if [ "${VSF_SKIP_SPEC_GUARD:-0}" = "1" ]; then
    return 0
  fi
  [ -d docs/spec_revision ] || return 0

  # GRAMMAR — BLOCKS, on STAGED files only. 2026-08-09.
  #
  # It was report-only because --strict called 13 of 40 CERTIFIED documents
  # INVALID and every class was the GRAMMAR being narrower than its own canon:
  #   7  domain_context `layer` enumerated S1..S5 while the corpus writes
  #      L+3, L..L+2, S4↔S4 — `layer` is a LOCUS, not a subsystem
  #  13  @ref fired on PROSE ABOUT @ref, inside the document that DEFINES it
  #   2  brace/bracket depth — the parser's own scanner treated \" as an
  #      escape where the corpus uses it as a delimiter, and desynchronised
  #   6  reused label Q1..Q3 — scoped by DOCUMENT, but they are field names in
  #      SIBLING blocks; depth cannot separate siblings, block IDENTITY can
  #   2  @status — one field, three senses (V-lifecycle, document-epistemic,
  #      operational health), one declared
  #   1  missing footer — covenant, a ratified exception
  #
  # Every one is now either declared in boot/vsl_language or delegated to the
  # tokenizer. 1 of 48 remains: covenant.vsm cites COVENANT_FLOW.vsm, which
  # does not exist. That is a real defect in a document that is rmw3's to
  # amend, so the gate blocks on what YOU stage — covenant blocks the commit
  # that touches covenant, and nothing else.
  #     debt(COVENANT-REF-BROKEN, class=doc, owner=rmw3, gate=covenant_1_2)
  if [ -f scripts/vsl/parser/vsl_parser.py ]; then
    _staged_vsm=$(git diff --cached --name-only --diff-filter=ACM \
                    | grep -E '^docs/spec_revision/.*\.vsm$' || true)
    if [ -n "$_staged_vsm" ]; then
      _bad=""
      for _f in $_staged_vsm; do
        [ -f "$_f" ] || continue
        if ! python3 scripts/vsl/parser/vsl_parser.py "$_f" --strict 2>&1 \
             | head -1 | grep -q "✓ VALID"; then
          _bad="$_bad $_f"
        fi
      done
      if [ -n "$_bad" ]; then
        echo "" >&2
        echo "❌ VSF grammar guard: staged .vsm does not parse --strict." >&2
        for _f in $_bad; do
          echo "      $_f" >&2
          python3 scripts/vsl/parser/vsl_parser.py "$_f" --strict 2>&1 \
            | grep -E "ERROR" | head -4 | sed 's/^/        /' >&2
        done
        exit 1
      fi
    fi
  fi

  # R15 ENVELOPE — BLOCKS. R15 says formal cross-agent exchange IS VSL, and
  # until 2026-08-10 nothing enforced that: envelope.py existed, passed its own
  # selftest, and was imported by NOTHING. 0 of 19 phi() blocks in the repo
  # parsed against it. rmw3 named it: "el envelope que escribimos de adorno".
  # The parser was the narrower of the two — it rejected the multi-line values
  # the protocol itself documents — so it was widened to the canon (R9: align,
  # never concede silently), and is now wired here. Blocks on what YOU stage,
  # same discipline as the grammar gate above: 9 pre-existing malformed headers
  # remain in archives and are not this commit's problem unless you touch them.
  if [ -f scripts/vsl/tools/envelope.py ]; then
    _staged_phi=$(git diff --cached --name-only --diff-filter=ACM | grep -E '\.vsm$' || true)
    if [ -n "$_staged_phi" ]; then
      if ! python3 scripts/vsl/tools/envelope.py check $_staged_phi; then
        echo "" >&2
        echo "❌ VSF R15 gate: a staged .vsm carries a phi() envelope that does not parse." >&2
        echo "   Fix the envelope, or remove the block if it was prose." >&2
        exit 1
      fi
    fi
  fi

  # NOT-PROSE — BLOCKS. VSL-GRAMMAR-REINFORCE (decision S5 rmw3 2026-08-14):
  # the ¬ glyph is a MATHEMATICAL OPERATOR in the ontology (boot/ canon,
  # vsl_language_primer) — never prose shorthand. Deterministic reinforcement:
  # a staged .vsm that introduces ¬ in prose (AFFIX/PROSE_AMB per not_census
  # v0.4 taxonomy) is blocked; LOGICAL (¬(…), ¬∃, ¬{…}, ¬Δ in formula context)
  # and TABLE (glyph declaration lines) stay legal. Same instrument as the
  # universe census (child/sandbox/vsl-notation-review/tools/not_census.py)
  # so the gate can never drift from the census. Verified: checks/not-prose-gate
  # (pass: flags prose ¬ rc=1; fail: negated claim false → discriminates).
  # Override with VSF_SKIP_SPEC_GUARD=1 — for a deliberate mid-fuse commit,
  # never to silence a finding.
  if [ -f scripts/vsl/validator/not_prose_gate.py ]; then
    _staged_vsm=$(git diff --cached --name-only --diff-filter=ACM \
                    | grep -E '^docs/spec_revision/.*\.vsm$' || true)
    if [ -n "$_staged_vsm" ]; then
      if ! python3 scripts/vsl/validator/not_prose_gate.py $_staged_vsm; then
        echo "" >&2
        echo "❌ VSF NOT-PROSE gate: staged .vsm introduces ¬ in prose." >&2
        echo "   ¬ is a mathematical operator (LOGICAL/TABLE legal); prose" >&2
        echo "   shorthand (¬word, do ¬x, sentence-final ¬) is blocked." >&2
        echo "   Rewrite the prose without ¬, or cite the formula it negates." >&2
        exit 1
      fi
    fi
  fi

  # SUPERSEDED 2026-08-28 (vOSLAB migration, rmw3 S5): ontology-master gates 8-10
  # are intentionally NOT enforced in vsf (they catalog parent sandbox WIP we leave
  # behind). Re-enable for a one-off audit with VSF_RUN_SUPERSEDED_GATES=1.
  if [ "${VSF_RUN_SUPERSEDED_GATES:-0}" = "1" ]; then
  # ONTOLOGY-MASTER-COHERENT — BLOCKS. The master (sandbox/
  # system_ontology_master.vsm) is the SCAFFOLD that catalogs every spec —
  # it is only useful if it does not lie: every spec() path in its catalog
  # must resolve to a real file/dir (R4 — the catalog is evidence, not
  # aspiration). A staged change to the master that introduces a path that
  # does not exist (or a spec that was never committed) is blocked here.
  # Verified: checks/ontology-master-coherent (pass: all paths resolve rc=0;
  # fail: fixture with nonexistent path flagged → discriminates).
  if [ -f docs/design/sandbox/system-ontology-master-v1/system_ontology_master.vsm ]; then
    if ! ./checks/ontology-master-coherent pass >/dev/null 2>&1; then
      echo "" >&2
      echo "❌ VSF ONTOLOGY-MASTER gate: catalog path does not resolve." >&2
      echo "   The master catalogs specs that are NOT on disk (or a path" >&2
      echo "   typo). Fix the master entry or commit the missing artifact." >&2
      ./checks/ontology-master-coherent pass 2>&1 >&2 | head -8
      exit 1
    fi
  fi

  # ONTOLOGY-MASTER-FRAME — BLOCKS. The master's vsm_frame rule: every spec
  # in the catalog declares its VSM organ (S1-S5, S3*) and recursion level,
  # and every real spec in sandbox/ is cataloged (backlog is the map). A
  # staged change that drops an organ=/recursion= or leaves a spec uncataloged
  # is blocked here. Verified: checks/ontology-master-frame (pass: vsm_frame
  # holds rc=0; fail: fixture with organ removed + orphan spec flagged →
  # discriminates).
  if [ -f docs/design/sandbox/system-ontology-master-v1/system_ontology_master.vsm ]; then
    if ! ./checks/ontology-master-frame pass >/dev/null 2>&1; then
      echo "" >&2
      echo "❌ VSF ONTOLOGY-MASTER gate: vsm_frame violated." >&2
      echo "   A spec is missing organ=/recursion= in the catalog, or a real" >&2
      echo "   sandbox/ spec is not cataloged (backlog is the map)." >&2
      ./checks/ontology-master-frame pass 2>&1 >&2 | head -8
      exit 1
    fi
  fi

  # ONTOLOGY-MASTER-TRACE — BLOCKS. The master's trace_rules rule 2: every
  # ontology task in TASKS.vsm cites its spec path (what:), and every
  # in-progress spec has its task. A staged TASKS.vsm change that introduces
  # an ontology task with no spec citation is blocked here. Verified:
  # checks/ontology-master-trace (pass: trace holds rc=0; fail: fixture with
  # spec-less ontology task flagged → discriminates).
  if [ -f docs/design/sandbox/system-ontology-master-v1/system_ontology_master.vsm ]; then
    if ! ./checks/ontology-master-trace pass >/dev/null 2>&1; then
      echo "" >&2
      echo "❌ VSF ONTOLOGY-MASTER gate: trace rule violated." >&2
      echo "   An ontology task in TASKS.vsm does not cite its spec path in" >&2
      echo "   what: (trace_rules rule 2 — nothing orphaned)." >&2
      ./checks/ontology-master-trace pass 2>&1 >&2 | head -8
      exit 1
    fi
  fi
  fi

  # BOOT-LOAD — BLOCKS. G_BOOT_CONSOLIDATION done_when #8 (boot_ontology_
  # pattern.vsm §7): "a clean boot load test runs: new session starts,
  # reminder fires, manifest read, verifier advisory passes, agent boots
  # within the token budget". Materialized as checks/boot-load-test: the
  # manifest is cited by every boot component (D1), the reminder is valid
  # with no CLAUDE.md pointer (D3), the verifier advisory passes, and the
  # boot docs fit the token budget. Verified: checks/boot-load-test (pass:
  # clean load rc=0; fail: fixture with uncited manifest flagged →
  # discriminates).
  if [ -f .opencode/agent/vsf-s3-planner.md ]; then
    if ! ./checks/boot-load-test pass >/dev/null 2>&1; then
      echo "" >&2
      echo "❌ VSF BOOT-LOAD gate: boot load broken." >&2
      echo "   A boot component no longer cites the manifest, the reminder" >&2
      echo "   regressed (D3), or the verifier advisory fails. Fix the boot" >&2
      echo "   before committing — the gate is G_BOOT_CONSOLIDATION #8." >&2
      ./checks/boot-load-test pass 2>&1 >&2 | head -10
      exit 1
    fi
  fi

  # PLAN-TREE — BLOCKS. rmw3 directive 2026-08-15: a plan is a LIVE TREE —
  # derived from the real tree + TASKS.vsm, never hand-written (R7 model≡
  # reality). Materialized as checks/plan-tree-valid: the declared plan()
  # progress: line must equal the derived one for every registered plan.
  # Verified: checks/plan-tree-valid (pass: no drift rc=0; fail: fixture
  # with corrupted progress flagged → discriminates). To re-sync: vsf-plan.
  if [ -f .opencode/command/vsf-plan.md ]; then
    if ! ./checks/plan-tree-valid pass >/dev/null 2>&1; then
      echo "" >&2
      echo "❌ VSF PLAN-TREE gate: a plan-tree block drifted from live state." >&2
      echo "   Re-derive with:  python3 scripts/plan/plan_tree.py --plan REVISION-ARC" >&2
      echo "   (or STRATEGIC) and update the plan doc, or fix the tree." >&2
      ./checks/plan-tree-valid pass 2>&1 >&2 | head -6
      exit 1
    fi
  fi

  # RELOCATE-VSM — BLOCKS. RELOCATE-VSM-SPEC done_when (sandbox proposal
  # 2026-08-14): after a doc relocation the corpus must carry ZERO new broken
  # refs vs the known baseline. Materialized as checks/relocate-vsm-valid:
  # reuses the SAME census instrument as scripts/shared/relocate_vsm.py, so the
  # gate can never drift from the plugin. Verified: checks/relocate-vsm-valid
  # (pass: 0 new broken rc=0; fail: fixture with nonexistent_doc ref flagged →
  # discriminates).
  if [ -f scripts/shared/relocate_vsm.py ]; then
    if ! ./checks/relocate-vsm-valid pass >/dev/null 2>&1; then
      echo "" >&2
      echo "❌ VSF RELOCATE-VSM gate: relocation left new broken refs." >&2
      echo "   A doc was moved without remapping its pinned refs. Run:" >&2
      echo "   python3 scripts/shared/relocate_vsm.py --from <old> --to <new>" >&2
      ./checks/relocate-vsm-valid pass 2>&1 >&2 | head -10
      exit 1
    fi
  fi

  # RELOCATE-VSM selftest — regression guard (runs only when the engine or
  # the check changed). RELOCATE-VSM-SPEC v1 done_when: round-trip a test
  # doc and confirm refs remapped, 0 broken. Materialized as
  # checks/relocate-vsm-valid selftest (C4 closure: spec enforced by gate).
  if git diff --cached --name-only --diff-filter=AM | grep -qE 'scripts/shared/relocate_vsm.py|checks/relocate-vsm-valid'; then
    if ! ./checks/relocate-vsm-valid selftest >/dev/null 2>&1; then
      echo "" >&2
