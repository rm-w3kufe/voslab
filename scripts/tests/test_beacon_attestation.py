#!/usr/bin/env python3
# design: docs/plans/p3_design_debt_2026_10_20.vsm (SUT: scripts/algedonic/beacon_attestation.py)
"""
test_beacon_attestation.py — BEACON-ACTIVATION end-to-end test.

Runs the full attestation protocol:
  1. Loads test CA
  2. Loads a test node cert (generated by gen_test_ca.sh)
  3. Builds a signed kernel_birth_payload
  4. Verifies the payload with BeaconAttestation
  5. Writes a registry entry (dry-run)

Usage:
  cd ~/vOSlab && scripts/s5-governance/gen_test_ca.sh && scripts/s5-governance/gen_test_ca.sh node vsf_nucleus
  python3 scripts/tests/test_beacon_attestation.py

Requires:
  - cryptography (Ed25519)
  - scripts/algedonic/beacon_attestation.py
  - _beacon_ca/ generated by gen_test_ca.sh
"""

import json
import os
import sys
import hashlib

# Add scripts/algedonic to path (beacon_attestation lives there post-migration)
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "algedonic"))
from beacon_attestation import (
    BeaconAttestation,
    build_kernel_payload,
    verify_node_cert,
    write_registry_entry,
)

CA_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "_beacon_ca")
REGISTRY_PATH = "/tmp/test_registry.jsonl"

# Clean up
if os.path.exists(REGISTRY_PATH):
    os.remove(REGISTRY_PATH)


def load_pubkey_hex() -> str:
    with open(os.path.join(CA_DIR, "ca.pubkey.hex")) as f:
        return f.read().strip()


def test_cert_verification():
    """Test cert chain verification."""
    print("=" * 60)
    print("TEST 1: Cert chain verification")
    print("=" * 60)

    ca_pubkey_hex = load_pubkey_hex()
    node_cert_path = os.path.join(CA_DIR, "nodes", "vsf_nucleus.cert.json")

    with open(node_cert_path) as f:
        node_cert = json.load(f)

    ok, reason, pubkey = verify_node_cert(node_cert, ca_pubkey_hex)
    assert ok, f"cert verification FAILED: {reason}"
    assert pubkey is not None
    assert len(pubkey) == 32
    print(f"  ✅ Cert valid: {reason}")
    print(f"  ✅ Node pubkey: {pubkey.hex()[:32]}…")
    print()


def test_full_attestation():
    """Test full attestation protocol: sign, verify, register."""
    print("=" * 60)
    print("TEST 2: Full attestation flow (sign → verify → register)")
    print("=" * 60)

    ca_pubkey_hex = load_pubkey_hex()
    node_key_path = os.path.join(CA_DIR, "nodes", "vsf_nucleus.key")

    # Compute a mock covenant SHA (just for testing)
    covenant_sha = hashlib.sha256(b"TEST_COVENANT_V1").hexdigest()
    calibration = hashlib.sha256(b"AXIS1_20260704_CALIBRATED").hexdigest()

    # Build signed payload
    payload = build_kernel_payload(
        kernel_id="vsf_nucleus",
        vsf_version="1.0.0-20260704",
        watermark="⟦ vsf_nucleus | rmw3 | vsm-1.0 | vsf.u2738.org ⟧",
        covenant_sha=covenant_sha,
        node_key_path=node_key_path,
        calibration=calibration,
    )

    assert payload["kernel_id"] == "vsf_nucleus"
    assert len(payload["sig"]) == 128
    assert payload["cert"]["node_id"] == "vsf_nucleus"
    assert payload["cert"]["pubkey_hex"]
    assert payload["cert"]["sig_hex"]
    print(f"  ✅ Payload built: kernel_id={payload['kernel_id']}")
    print(f"  ✅ Signature: {payload['sig'][:32]}…")
    print(f"  ✅ Cert: node_id={payload['cert']['node_id']}")

    # Verify
    verifier = BeaconAttestation(ca_pubkey_hex, current_covenant_sha=covenant_sha)
    result = verifier.verify(payload)

    assert result["status"] == "trusted", f"Verification FAILED: {result['reason']}"
    print(f"  ✅ Verification: {result['status']}")
    print(f"  ✅ Reason: {result['reason']}")

    # Write registry
    entry = write_registry_entry(REGISTRY_PATH, result, remote_ip="10.10.20.1")
    assert entry["status"] == "trusted"
    print(f"  ✅ Registry entry written to {REGISTRY_PATH}")
    with open(REGISTRY_PATH) as f:
        print(f"     Entry: {f.read().strip()}")
    print()


def test_rejected_cases():
    """Test various rejection scenarios."""
    print("=" * 60)
    print("TEST 3: Rejection scenarios")
    print("=" * 60)

    ca_pubkey_hex = load_pubkey_hex()
    node_key_path = os.path.join(CA_DIR, "nodes", "vsf_nucleus.key")
    covenant_sha = hashlib.sha256(b"TEST_COVENANT_V1").hexdigest()

    # Build a valid payload first
    payload = build_kernel_payload(
        kernel_id="vsf_nucleus",
        vsf_version="1.0.0",
        watermark="⟦ test ⟧",
        covenant_sha=covenant_sha,
        node_key_path=node_key_path,
    )

    # Test 3a: Wrong covenant
    verifier = BeaconAttestation(ca_pubkey_hex, current_covenant_sha="0" * 64)
    result = verifier.verify(payload)
    assert result["status"] == "rejected"
    assert "covenant_sha" in result["reason"]
    print(f"  3a ❌ Wrong covenant: {result['reason'][:60]}…")

    # Test 3b: Tampered sig
    bad_payload = dict(payload)
    bad_payload["sig"] = "0" * 128
    verifier = BeaconAttestation(ca_pubkey_hex, current_covenant_sha=covenant_sha)
    result = verifier.verify(bad_payload)
    assert result["status"] == "rejected"
    assert "signature" in result["reason"]
    print(f"  3b ❌ Bad signature: {result['reason'][:60]}…")

    # Test 3c: Wrong CA pubkey
    wrong_ca = "1" * 64
    verifier = BeaconAttestation(wrong_ca, current_covenant_sha=covenant_sha)
    result = verifier.verify(payload)
    assert result["status"] == "rejected"
    assert "CA mismatch" in result["reason"]
    print(f"  3c ❌ Wrong CA: {result['reason'][:60]}…")

    # Test 3d: Missing cert
    no_cert_payload = dict(payload)
    del no_cert_payload["cert"]
    verifier = BeaconAttestation(ca_pubkey_hex, current_covenant_sha=covenant_sha)
    result = verifier.verify(no_cert_payload)
    assert result["status"] == "rejected"
    assert "missing" in result["reason"]
    print(f"  3d ❌ Missing cert: {result['reason'][:60]}…")

    print()
    print("  ✅ All rejection scenarios pass")


def main():
    if not os.path.exists(os.path.join(CA_DIR, "ca.key")):
        print(f"ERROR: Test CA not found at {CA_DIR}/")
        print("Run:  scripts/s5-governance/gen_test_ca.sh && scripts/s5-governance/gen_test_ca.sh node vsf_nucleus")
        sys.exit(1)

    node_cert = os.path.join(CA_DIR, "nodes", "vsf_nucleus.cert.json")
    if not os.path.exists(node_cert):
        print(f"ERROR: Node cert not found at {node_cert}")
        print("Run:  scripts/s5-governance/gen_test_ca.sh node vsf_nucleus")
        sys.exit(1)

    test_cert_verification()
    test_full_attestation()
    test_rejected_cases()

    print("=" * 60)
    print(f"ALL TESTS PASSED")
    print("=" * 60)
    print(f"CA pubkey hex: {load_pubkey_hex()}")
    print(f"Registry path: {REGISTRY_PATH}")


if __name__ == "__main__":
    main()
